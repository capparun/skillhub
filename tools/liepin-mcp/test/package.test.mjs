import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import crypto from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {pathToFileURL,fileURLToPath} from 'node:url';
import {buildPackage} from '../scripts/build-package.mjs';
test('build CLI invoked through a directory alias actually creates the package',{skip:process.platform==='win32'},t=>{
 const temp=fs.mkdtempSync(path.join(os.tmpdir(),'hunter-build-alias-'));
 t.after(()=>fs.rmSync(temp,{recursive:true,force:true}));
 const alias=path.join(temp,'source');
 fs.symlinkSync(fileURLToPath(new URL('../scripts/',import.meta.url)),alias,'dir');
 const output=path.join(temp,'candidate');
 const run=spawnSync(process.execPath,[path.join(alias,'build-package.mjs'),output,'site-adapter'],{encoding:'utf8'});
 assert.equal(run.status,0,run.stderr);
 assert.equal(JSON.parse(run.stdout).root,path.resolve(output));
 assert.equal(JSON.parse(fs.readFileSync(path.join(output,'manifest.json'))).delivery,'site-adapter');
});
test('candidate package is source-bound and serves local MCP tools outside the repo',t=>{
 const temp=fs.mkdtempSync(path.join(os.tmpdir(),'hunter-package-'));t.after(()=>fs.rmSync(temp,{recursive:true,force:true}));
 const a=buildPackage(path.join(temp,'候选 包 a')),b=buildPackage(path.join(temp,'候选 包 b'));assert.equal(a.sourceFingerprint,b.sourceFingerprint);
 const manifest=JSON.parse(fs.readFileSync(path.join(a.root,'manifest.json')));
 assert.ok(manifest.files.some(file=>file.path==='tools/liepin-mcp/skill/hunter-liepin-mcp/SKILL.md'));
 assert.ok(manifest.files.some(file=>file.path==='tools/liepin-mcp/skill/hunter-liepin-mcp/references/workflow.md'));
 for(const file of manifest.files)assert.equal(file.path.includes('\\'),false,'manifest paths must be portable');
 for(const file of manifest.files)assert.equal(crypto.createHash('sha256').update(fs.readFileSync(path.join(a.root,file.path))).digest('hex'),file.sha256);
 const messages=[{id:1,method:'tools/list'},{id:2,method:'tools/call',params:{name:'liepin_conditions',arguments:{}}}];
 const run=spawnSync(process.execPath,[path.join(a.root,'tools/liepin-mcp/server.mjs')],{cwd:temp,input:messages.map(m=>JSON.stringify({jsonrpc:'2.0',...m})).join('\n')+'\n',encoding:'utf8',env:{PATH:'/nonexistent',HUNTER_MCP_COMMAND:'/nonexistent'}});
 assert.equal(run.status,0,run.stderr);const responses=run.stdout.trim().split('\n').map(JSON.parse);assert.equal(responses[0].result.tools.length,19);assert.equal(JSON.parse(responses[1].result.content[0].text).length,30);
 assert.throws(()=>buildPackage(a.root),/不覆盖/);
});
test('site adapter candidate excludes independent server and runs local entry outside repository',t=>{
 const temp=fs.mkdtempSync(path.join(os.tmpdir(),'hunter-adapter-package-'));t.after(()=>fs.rmSync(temp,{recursive:true,force:true}));
 const candidate=buildPackage(path.join(temp,'候选 包'),{delivery:'site-adapter'});
 const manifest=JSON.parse(fs.readFileSync(path.join(candidate.root,'manifest.json')));
 assert.equal(manifest.delivery,'site-adapter');assert.equal(fs.existsSync(path.join(candidate.root,'tools/liepin-mcp/server.mjs')),false);
 assert.equal(manifest.files.filter(f=>f.path.startsWith('tools/liepin-mcp/adapters/liepin/')).length,15);
 assert.ok(manifest.files.some(f=>f.path==='tools/liepin-mcp/adapters/liepin/favorite-list.js'));
 assert.ok(manifest.files.some(f=>f.path==='tools/liepin-mcp/compat/adapter-tabs.mjs'));
 const launcherModule=pathToFileURL(path.join(candidate.root,'tools/liepin-mcp/scripts/build-native-launcher.mjs')).href;
 const imported=spawnSync(process.execPath,['--input-type=module','-e',`const m=await import(${JSON.stringify(launcherModule)});if(typeof m.buildNativeLauncher!=='function')process.exit(1);`],{cwd:temp,encoding:'utf8'});
 assert.equal(imported.status,0,imported.stderr);
 const pkg=JSON.parse(fs.readFileSync(path.join(candidate.root,'package.json')));
 assert.deepEqual(pkg.bin,{'hunter-liepin-local':'tools/liepin-mcp/local.mjs'});
 const run=spawnSync(process.execPath,[path.join(candidate.root,'tools/liepin-mcp/local.mjs'),'conditions'],{cwd:temp,encoding:'utf8'});
 assert.equal(run.status,0,run.stderr);assert.equal(JSON.parse(run.stdout).length,30);
});
