import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import {PATCHED_BACKGROUND_SHA256,verifyCompatManifest} from './lib/compat-build.mjs';
const root=process.argv[2];if(!root)throw Error('需要构建目录');
const source=fs.readFileSync(path.join(root,'background.js'),'utf8');
assert.equal(crypto.createHash('sha256').update(source).digest('hex'),PATCHED_BACKGROUND_SHA256);
verifyCompatManifest(JSON.parse(fs.readFileSync(path.join(root,'manifest.json'))));
const start=source.indexOf('async function evaluateMain('),end=source.indexOf('\nasync function callPage(',start);
assert.ok(start>=0&&end>start);
const calls=[];
const context={ensureAttached:async()=>{},evaluate:async()=>({main:true}),frameHosts:new Map(),mainContexts:new Map(),key2:(a,b)=>a+':'+b,hasFrameTarget:async()=>false,sendDebuggerCommand:async(_,method)=>calls.push(method)};
vm.createContext(context);vm.runInContext(source.slice(start,end)+'\nglobalThis.run=evaluateMain;',context);
assert.equal((await context.run(1,null,'1',false,1000)).main,true);
await assert.rejects(context.run(1,'frame-1','1',false,1000),e=>e.code==='hunter_frame_unsupported');
assert.deepEqual(calls,[]);
const build=JSON.parse(fs.readFileSync(path.join(root,'hunter-build.json')));
assert.equal(build.permissionsChanged,false);
console.log(JSON.stringify({mainWorld:true,iframeImplicitSubscription:'blocked-before-send',unexpectedCdpCalls:calls,build:build.version}));
